# Generates the quarter-wave sine table shared by the Solana program (Rust) and
# the Unity client (C#). Both must hold exactly the same integers, or a replay
# verified on-chain would not match the run the player drove.
# Usage: python tools/gen-sin-table.py
import math
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
vals = [round(math.sin(i / 4096.0 * 2 * math.pi) * 65536) for i in range(1025)]

rust = "// Generated by tools/gen-sin-table.py. Do not edit.\n\npub const SIN_QUARTER: [i32; 1025] = [\n"
for i in range(0, 1025, 8):
    rust += "    " + ", ".join(str(v) for v in vals[i : i + 8]) + ",\n"
rust += "];\n"
(root / "pixelvault/programs/pixelvault/src/sim/sin_table.rs").write_text(rust, encoding="utf-8", newline="")

cs = "// Generated by tools/gen-sin-table.py. Do not edit.\n\npublic static class SinTable\n{\n    public static readonly int[] Quarter = {\n"
for i in range(0, 1025, 8):
    cs += "        " + ", ".join(str(v) for v in vals[i : i + 8]) + ",\n"
cs += "    };\n}\n"
(root / "game/Assets/Scripts/Sim/SinTable.cs").write_text(cs, encoding="utf-8", newline="")

print(f"wrote {len(vals)} entries")
